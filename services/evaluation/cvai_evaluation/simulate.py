"""Synthetic ratings — **for testing the pipeline, never for drawing conclusions**.

Every function here invents numbers. They exist so that aggregation, gap-to-anchor and
report rendering can be exercised end to end before any human has listened to anything,
and so the tests have deterministic input.

Anything produced here is written with ``"synthetic": true`` inside the file and a
``rater_id`` prefixed ``sim-``, so a simulated rating set cannot be mistaken for real
data further down the line.
"""

from __future__ import annotations

import json
import random
from pathlib import Path

from cvai_types import BlindKey, HumanRating

SYNTHETIC_RATER_PREFIX = "sim-"


def simulate_ratings(
    key: BlindKey,
    *,
    n_raters: int = 3,
    seed: int = 7,
    candidate_bias: dict[str, float] | None = None,
    ground_truth_bonus: float = 1.2,
    rater_noise: float = 0.6,
) -> list[HumanRating]:
    """Invent plausible ratings.

    Ground-truth items score higher by ``ground_truth_bonus``, which is what a working
    listening test should also show — if real recordings do not beat the candidates, the
    raters were not discriminating, and the simulation reproduces that shape so the
    report's anchor logic is actually tested.
    """
    rng = random.Random(seed)
    bias = candidate_bias or {}
    ratings: list[HumanRating] = []

    for index in range(n_raters):
        rater_id = f"{SYNTHETIC_RATER_PREFIX}{index + 1}"
        # Each rater has a personal offset: some are generous, some are harsh.
        rater_offset = rng.uniform(-0.4, 0.4)
        for entry in key.entries:
            base = 3.0 + bias.get(entry.candidate_id, 0.0) + rater_offset
            if entry.is_ground_truth:
                base += ground_truth_bonus

            def score() -> int:
                return _clamp(base + rng.gauss(0.0, rater_noise))

            speaker = score()
            natural = score()
            character = score()
            # Artifact level runs the other way: better systems sound less generated.
            artifact = _clamp(6.0 - (base + rng.gauss(0.0, rater_noise)))

            ratings.append(
                HumanRating(
                    rater_id=rater_id,
                    item_id=entry.item_id,
                    speaker_similarity=speaker,
                    naturalness=natural,
                    character_similarity=character,
                    ai_artifact_level=artifact,
                    believed_real=(natural + speaker) / 2.0 >= 4.0,
                    comment="",
                )
            )
    return ratings


def write_ratings(ratings: list[HumanRating], path: Path) -> Path:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    payload = {
        "synthetic": True,
        "warning": "Generated by cvai_evaluation.simulate — not human ratings.",
        "ratings": [r.model_dump(mode="json") for r in ratings],
    }
    path.write_text(
        json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    return path


def _clamp(value: float) -> int:
    return max(1, min(5, int(round(value))))
