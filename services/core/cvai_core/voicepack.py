"""Voice pack scaffolding and validation.

The validator is the quality gate between Milestone 2 and Milestone 3: it answers "is
this pack good enough to start training on?" before a GPU-hour is spent. Most of its
checks map directly onto failure modes listed in spec §27 — a pack that only has one
reference clip per style, or whose styles have no audio at all, will produce exactly the
"identical intonation across all sentences" result the spec warns about, and it is much
cheaper to see that here than after a listening test.
"""

from __future__ import annotations

from enum import Enum
from pathlib import Path

from cvai_types import (
    CharacterProfile,
    CoreStyle,
    CVAIModel,
    DatasetManifest,
    DatasetSplit,
    ReferenceBank,
    VoicePackManifest,
)
from pydantic import Field

from .loaders import (
    load_voicepack_manifest,
    save_model_yaml,
    try_load_dataset_manifest,
    try_load_reference_bank,
)
from .paths import VoicePackPaths

#: Spec §19 asks for roughly 20-60 minutes of high-quality character speech.
MIN_RECOMMENDED_MINUTES = 20.0
MAX_USEFUL_MINUTES = 60.0
#: Below this, a style's reference clips cannot rotate and every line in that style will
#: be conditioned on the same audio.
MIN_REFERENCES_PER_STYLE = 2


class Severity(str, Enum):
    ERROR = "error"
    WARNING = "warning"
    INFO = "info"


class Issue(CVAIModel):
    severity: Severity
    code: str
    message: str
    context: dict[str, object] = Field(default_factory=dict)


class ValidationReport(CVAIModel):
    voicepack_id: str
    root: str
    issues: list[Issue] = Field(default_factory=list)
    stats: dict[str, object] = Field(default_factory=dict)

    @property
    def ok(self) -> bool:
        return not any(i.severity is Severity.ERROR for i in self.issues)

    def errors(self) -> list[Issue]:
        return [i for i in self.issues if i.severity is Severity.ERROR]

    def warnings(self) -> list[Issue]:
        return [i for i in self.issues if i.severity is Severity.WARNING]

    def render(self) -> str:
        lines = [f"Voice pack: {self.voicepack_id}  ({self.root})"]
        if self.stats:
            lines.append("")
            lines.append("Stats")
            for key, value in self.stats.items():
                lines.append(f"  {key}: {value}")
        symbol = {Severity.ERROR: "✗", Severity.WARNING: "!", Severity.INFO: "·"}
        if self.issues:
            lines.append("")
            lines.append("Findings")
            for issue in self.issues:
                lines.append(f"  {symbol[issue.severity]} [{issue.code}] {issue.message}")
        lines.append("")
        lines.append("PASS" if self.ok else "FAIL")
        return "\n".join(lines)


