_README = """# Voice Pack: {display_name} (`{voicepack_id}`)

Generated by `cvai-voicepack init`. See `docs/VOICEPACK.md` for the full pipeline.

## Rules

1. **`raw/` is immutable.** Drop original audio here once and never write to it again.
   Every other directory can be deleted and regenerated from `raw/` plus the manifest.
2. **Optional cleaning stays off unless the audio needs it.** Source separation,
   de-reverb and denoising each remove part of the performance. Turn one on only after
   listening to what it does to this character, and record it in `processing_chain`.
3. **Reference clips need transcripts.** Several engines require the reference text, and
   a bank without it has to be rebuilt by hand.
4. **Keep at least two reference clips per style.** One clip per style means every line
   in that style is conditioned on the same audio.

## Layout

| Directory | Contents |
|---|---|
| `raw/` | untouched originals |
| `processed/` | intermediate stage outputs, regenerable |
| `clean/` | human-approved training audio |
| `rejected/` | filtered-out clips, kept with the reason |
| `transcripts/` | ASR output and human corrections |
| `metadata/` | `voicepack.yaml`, `dataset.json`, `references.json` |
| `references/` | Reference Bank, one subdirectory per style |
| `datasets/` | engine-specific exports |
| `checkpoints/` | character-specific fine-tuned models |
| `evaluation/` | benchmark runs and listening-test results |
"""


def scaffold_voicepack(
    paths: VoicePackPaths,
    manifest: VoicePackManifest,
    *,
    overwrite: bool = False,
) -> ValidationReport:
    """Create the directory tree and write the manifest."""
    if paths.manifest_file.exists() and not overwrite:
        raise FileExistsError(
            f"{paths.manifest_file} already exists; pass overwrite=True to replace it"
        )

    for directory in paths.all_dirs():
        directory.mkdir(parents=True, exist_ok=True)
        keep = directory / ".gitkeep"
        if not any(directory.iterdir()):
            keep.touch()

    # One subdirectory per declared style, so the bank's shape is obvious on disk even
    # before any clips exist (spec §10).
    for style in manifest.styles:
        style_dir = paths.references / style.name
        style_dir.mkdir(parents=True, exist_ok=True)
        if not any(style_dir.iterdir()):
            (style_dir / ".gitkeep").touch()

    save_model_yaml(manifest, paths.manifest_file)
    (paths.root / "README.md").write_text(
        _README.format(
            display_name=manifest.display_name, voicepack_id=manifest.voicepack_id
        ),
        encoding="utf-8",
    )
    return validate_voicepack(paths)


def default_styles() -> list[dict[str, str]]:
    """The core taxonomy (spec §9) as plain dicts, for building a starter manifest."""
    return [{"name": s.value, "core_style": s.value} for s in CoreStyle]


